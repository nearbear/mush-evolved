// Writes Mush/derived/asset-index.txt: every file under Mush/ with its size,
// one per line, so the archive can be searched by name without opening the
// art itself (project settings deny reading Mush/www and Mush/clients).
//
// Run with `npm run asset-index` after adding or removing files in Mush/.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";

const MUSH = resolve(import.meta.dirname, "../../../Mush");
const OUTPUT = resolve(MUSH, "derived/asset-index.txt");
/** Our own output and tooling, not archive content. */
const SKIP = new Set(["derived", "node_modules"]);

function walk(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (dir === MUSH && SKIP.has(entry.name)) continue;
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (entry.isFile()) out.push(`${relative(MUSH, path)}\t${statSync(path).size}`);
  }
}

const lines: string[] = [];
walk(MUSH, lines);
writeFileSync(
  OUTPUT,
  `# Every file under Mush/ (path relative to Mush/, then size in bytes). Generated by npm run asset-index.\n${lines.join("\n")}\n`,
);
console.log(`Wrote ${lines.length} entries to ${relative(process.cwd(), OUTPUT)}`);
